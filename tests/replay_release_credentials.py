"""Replay the SEC-010 proof: before and after, mutation, static analysis.

Usage, from the repository root:
  python3 -B tests/replay_release_credentials.py [before|after|mutation|static] ...

With no argument every phase runs, in that order. No CI job runs this script: it is the
one-command replay of the evidence quoted in the pull request. Requirements: Git history
(BEFORE must be reachable), Python 3 with pytest and PyYAML, Bash, OpenSSH 8.9 or later;
the static phase also needs actionlint 1.7.12, ShellCheck 0.11.0 and zizmor 1.31.1 on PATH
(their versions are checked, not assumed). Only fixture keys generated by the tests are used.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BEFORE = "02c1fb5b795d409c3728eda6f690e10a2f9d8df7"  # PR #275 head the Spec bench refuted
LIFETIME = "tests/test_ci_release_credential_lifetime.py"
COPIES = (".github/workflows/pipeline.yml", ".github/workflows/pipeline-post-merge.yml",
          "templates/ci/pipeline.yml", "templates/ci/native/pipeline.yml",
          "templates/ci/native/generated/pipeline.yml")
EXPECTED_BEFORE = {
    "test_runner_sigint_releases_the_key_within_its_window",
    "test_runner_sigterm_releases_the_key_within_its_window",
    "test_second_signal_during_release_does_not_cut_it_short",
    "test_agent_that_ignores_sigterm_is_killed_and_fails_the_step",
    "test_publisher_that_ignores_sigterm_is_killed_within_the_bound",
    "test_killed_step_leaves_an_agent_that_stops_by_itself",
}
STEP = "          "  # indentation of the publish body inside the workflow
# (label, exact text in the step, replacement). Each must make the lifetime suite fail.
MUTANTS = (
    ("no exec: a second shell sits between the runner and the agent",
     "exec ssh-agent -a", "ssh-agent -a"),
    ("socket under RUNNER_TEMP", '"${TMPDIR:-/tmp}/release-agent.XXXXXX"', '"$RUNNER_TEMP/release-agent.XXXXXX"'),
    ("AGENT_DIR not exported", 'export AGENT_DIR="$agent_dir"', 'AGENT_DIR="$agent_dir"'),
    ("second signal not ignored", "trap '' INT TERM\n", ":\n"),
    ("status of the step lost", "status=$?\n" + STEP + "  trap", "status=0\n" + STEP + "  trap"),
    ("no SIGTERM sent", 'do kill -TERM "$pid" 2>/dev/null || :; done', "do :; done"),
    ("agent not sent SIGTERM", 'for pid in $publisher "$SSH_AGENT_PID"; do kill -TERM',
     "for pid in $publisher; do kill -TERM"),
    ("no wait before SIGKILL", "$(seq 50)", "$(seq 0)"),
    ("unbounded wait", "sleep 0.1\n", "sleep 2\n"),
    ("agent not awaited", 'kill -0 $publisher "$SSH_AGENT_PID" 2>/dev/null || break',
     "kill -0 $publisher 2>/dev/null || break"),
    ("no SIGKILL", 'kill -KILL "$pid"\n', ":\n"),
    ("no visible error", 'echo "::error::release process $pid did not stop on SIGTERM"\n', ":\n"),
    ("forced kill does not fail the step", '[ "$status" -ne 0 ] || status=1\n', ":\n"),
    ("socket not removed", 'rm -f -- "$SSH_AUTH_SOCK"\n', ":\n"),
    ("socket directory not removed", 'rmdir -- "$AGENT_DIR" || status=1\n', ":\n"),
    ("socket directory failure hidden", 'rmdir -- "$AGENT_DIR" || status=1\n', 'rmdir -- "$AGENT_DIR" || :\n'),
    ("release status not returned", 'exit "$status"\n' + STEP + "}", ":\n" + STEP + "}"),
    ("no release trap", "trap release EXIT\n", ":\n"),
    ("INT trap removed: bash dies of SIGINT before the release", "trap 'exit 130' INT\n", ":\n"),
    ("TERM trap removed", "trap 'exit 143' TERM\n", ":\n"),
    ("raw key left in the environment", "unset SSH_KEY\n", ":\n"),
    ("publisher in the foreground", "python3 - <<'PY' &\n", "python3 - <<'PY'\n"),
    ("publisher not tracked", "publisher=$!\n", "publisher=\n"),
    ("publisher status lost", 'exit "$status"\n' + STEP + "PUBLISH", ":\n" + STEP + "PUBLISH"),
    ("publisher ignores the release", "signal.signal(signal.SIGTERM, lambda *_: sys.exit(143))",
     "pass"),
    ("host ssh configuration read", "ssh -F /dev/null", "ssh"),
    ("agent identity refused", "IdentitiesOnly=no", "IdentitiesOnly=yes"),
    ("runner key files offered", "-o IdentityFile=none ", ""),
    ("host key not checked", "StrictHostKeyChecking=yes", "StrictHostKeyChecking=no"),
    ("runner export", "unset SSH_KEY\n", 'unset SSH_KEY\n' + STEP + 'echo canary >> "$GITHUB_ENV"\n'),
    ("second agent", "unset SSH_KEY\n", "unset SSH_KEY\n" + STEP + "ssh-agent /bin/true\n"),
)
# Mutants that no test can tell apart from the code, with the reason (see the PR body).
EQUIVALENT = {
    "publisher kept after wait": ("          publisher=\n          exit", "          exit"),
}


def pytest(args, env=None):
    command = [sys.executable, "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider", *args]
    return subprocess.run(command, cwd=ROOT, env=dict(os.environ, **(env or {})), capture_output=True, text=True)


def failed_tests(output):
    return {re.sub(r"\[.*", "", name) for name in re.findall(r"^FAILED \S+::(\S+)", output, re.M)}


def suite_over(paths, extra=()):
    return pytest([LIFETIME, *extra], {"RELEASE_CREDENTIAL_WORKFLOWS": os.pathsep.join(map(str, paths))})


def before(scratch):
    paths = []
    for name in COPIES:
        path = scratch / name.replace("/", "_")
        path.write_bytes(subprocess.check_output(["git", "show", f"{BEFORE}:{name}"], cwd=ROOT))
        paths.append(path)
    result = suite_over(paths)
    failed = failed_tests(result.stdout)
    if failed != EXPECTED_BEFORE:
        raise SystemExit(f"before {BEFORE[:7]}: unexpected failures {sorted(failed)}\n{result.stdout}")
    print(f"before {BEFORE[:7]}: {result.stdout.strip().splitlines()[-1]} (the expected {len(failed)})")


def after(_scratch):
    result = pytest([LIFETIME, "tests/test_ci_tag_publish.py", "tests/test_ci_tag_no_checkout.py",
                     "tests/test_ci_template.py", "tests/test_ci_post_merge_template.py"])
    if result.returncode != 0:
        raise SystemExit(result.stdout + result.stderr)
    print("after: " + result.stdout.strip().splitlines()[-1])


def mutate(text, original, replacement, label):
    if text.count(original) != 1:
        raise SystemExit(f"mutation anchor for {label!r} matches {text.count(original)} times")
    return text.replace(original, replacement)


def mutation(scratch):
    source = (ROOT / COPIES[0]).read_text()
    survivors = []
    for index, (label, original, replacement) in enumerate(MUTANTS):
        path = scratch / f"mutant-{index}.yml"
        path.write_text(mutate(source, original, replacement, label))
        result = suite_over([path], ["-x"])
        killed = result.returncode == 1 and failed_tests(result.stdout)
        print(f"mutant {index:2} {'killed' if killed else 'SURVIVED'}: {label}"
              + (f" by {sorted(failed_tests(result.stdout))[0]}" if killed else ""), flush=True)
        if not killed:
            survivors.append(label)
    for label, (original, replacement) in EQUIVALENT.items():
        path = scratch / "equivalent.yml"
        path.write_text(mutate(source, original, replacement, label))
        state = "passes (equivalent)" if suite_over([path]).returncode == 0 else "killed"
        print(f"equivalent {label}: {state}", flush=True)
    if survivors:
        raise SystemExit(f"{len(survivors)} surviving mutants: {survivors}")
    print(f"mutation: {len(MUTANTS)} of {len(MUTANTS)} killed")


def inner_script(workflow):
    steps = yaml.safe_load(workflow.read_text())["jobs"]["tag"]["steps"]
    body = next(step for step in steps if step.get("id") == "publish")["run"]
    inner = body.split("<<'PUBLISH'\n", 1)[1].rsplit("PUBLISH\n", 1)[0]
    return "#!/usr/bin/env bash\nset -euo pipefail\n" + inner


def check_version(command, expected):
    if expected not in subprocess.check_output(command, text=True):
        raise SystemExit(f"{command[0]}: expected {expected}")


def zizmor_counts(directory, files):
    command = ["zizmor", "--offline", "--no-config", "--no-exit-codes", "--format", "json", *files]
    findings = yaml.safe_load(subprocess.check_output(command, cwd=directory))
    return Counter((item["ident"], item["determinations"]["severity"]) for item in findings)


def static(scratch):
    check_version(["actionlint", "-version"], "1.7.12")
    check_version(["shellcheck", "--version"], "version: 0.11.0")
    check_version(["zizmor", "--version"], "zizmor 1.31.1")
    files = [*COPIES[:2], ".github/workflows/codeql.yml", ".github/workflows/release.yml", *COPIES[2:]]
    subprocess.run(["actionlint", "-shellcheck", "shellcheck", *files], cwd=ROOT, check=True)
    inner = scratch / "publish-inner.sh"
    inner.write_text(inner_script(ROOT / COPIES[0]))
    # Three info notes are deliberate: SC2329 (release runs from a trap), SC2086 (an
    # empty $publisher must expand to no argument), SC2016 (Git's shell expands
    # GIT_SSH_COMMAND). Every warning and error fails the replay.
    subprocess.run(["shellcheck", "-s", "bash", "-S", "warning", str(inner)], check=True)
    old = scratch / "zizmor-before"
    for name in files:
        (old / name).parent.mkdir(parents=True, exist_ok=True)
        (old / name).write_bytes(subprocess.check_output(["git", "show", f"{BEFORE}:{name}"], cwd=ROOT))
    baseline, current = zizmor_counts(old, files), zizmor_counts(ROOT, files)
    if current - baseline:
        raise SystemExit(f"new zizmor findings: {current - baseline}")
    print(f"static: actionlint+shellcheck clean on {len(files)} workflows, inner publish script clean; "
          f"zizmor {sum(baseline.values())} before, {sum(current.values())} now, 0 new")


PHASES = {"before": before, "after": after, "mutation": mutation, "static": static}


def main(argv):
    with tempfile.TemporaryDirectory(prefix="sec010-replay-") as tmp:
        for name in argv or list(PHASES):
            directory = Path(tmp) / name
            directory.mkdir()
            PHASES[name](directory)


if __name__ == "__main__":
    main(sys.argv[1:])
