#!/usr/bin/env python3
"""Generate rules/agent-routing-table.md — the compact routing table.

One line per genius agent (name + shape keywords + one-line description),
generated purely from agent frontmatter. Only genius agents exist (owner
decision 2026-10-21: the team-role agents were removed). Routing consumers (the delegating session, genius:route,
genius:index) read THIS file instead of the 132KB INDEX.md or full agent files.
Lives under rules/ (installed to ~/.claude/rules/) — NOT under agents/, where
Claude Code would parse it as a bogus agent definition.

Usage:
  scripts/generate-routing-table.py            # regenerate rules/agent-routing-table.md
  scripts/generate-routing-table.py --check    # exit 1 if the table is stale
"""
import json
import re
import sys
import glob
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "rules", "agent-routing-table.md")
ROUTES = os.path.join(REPO, "rules", "agent-routes.json")


def _decode_escapes(val):
    """Undo JSON double-encoding (\\uXXXX, \\") until the value is stable."""
    while "\\u" in val or '\\"' in val:
        try:
            decoded = val.replace('\\"', '"').encode().decode("unicode_escape")
        except UnicodeDecodeError:
            break
        if decoded == val:
            break
        val = decoded
    return val


def frontmatter(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    fm = {}
    for key in ("name", "description", "when_to_use", "model", "shapes"):
        km = re.search(rf"^{key}:\s*(.+)$", m.group(1), re.M)
        if km:
            val = _decode_escapes(km.group(1).strip().strip('"'))
            fm[key] = val.strip('"').strip()
    return fm


def row(fm, shapes_col):
    name = fm.get("name", "?")
    desc = fm.get("description", "").replace("|", "/")
    when = fm.get("when_to_use", "").replace("|", "/")
    trig = shapes_col.replace("|", "/") if shapes_col else when
    return f"| {name} | {trig} | {desc} |"


def routes_section():
    """Task class -> built-in subagent + genius patterns, from rules/agent-routes.json."""
    with open(ROUTES, encoding="utf-8") as fh:
        data = json.load(fh)
    lines = [
        "",
        "## Task classes (route by task, then add the genius pattern)",
        "",
        "Delegate to a Claude Code built-in `subagent_type` (never to a genius file) and put",
        "`GENIUS: <name>[, <name>]` on its own line in the prompt, naming 1 or 2 rows of the",
        "table above whose method the delegate must apply. `hooks/pre-agent-genius-gate.py`",
        "denies an Agent call without it. Source: `rules/agent-routes.json`.",
        "",
        "| Task class | subagent_type | GENIUS line |",
        "|---|---|---|",
    ]
    for r in data["routes"]:
        lines.append(f"| {r['task_class']} | {r['subagent_type']} | "
                     f"{', '.join(r['geniuses'])} |")
    lines += ["", f"No task class matches: `GENIUS: {', '.join(data['fallback_geniuses'])}`."]
    return lines


def build():
    lines = [
        "# Agent Routing Table — generated, do not edit",
        "",
        "Generated by `scripts/generate-routing-table.py` from agent frontmatter and",
        "`rules/agent-routes.json`. Route from THIS table only: match the problem against",
        "trigger keywords and descriptions, then delegate to a built-in subagent with a",
        "`GENIUS:` line (see the task-class table at the end). Do NOT Read full agent files or",
        "`agents/genius/INDEX.md` to make a routing decision — INDEX.md is for",
        "human deep-dives and targeted `grep` (via `tools/shape-router.sh` /",
        "`tools/genius-invoker.sh route`), never a full-file Read.",
        "",
        "## Genius agents (route by problem shape)",
        "",
        "| Agent | Shapes (trigger keywords) | Description |",
        "|---|---|---|",
    ]
    genius = sorted(
        f for f in glob.glob(os.path.join(REPO, "agents", "genius", "*.md"))
        if not f.endswith("INDEX.md") and not f.endswith("ROUTING.md")
    )
    for f in genius:
        fm = frontmatter(f)
        if not fm or "name" not in fm:
            continue
        shapes = fm.get("shapes", "").strip("[]").replace(",", ", ").replace("  ", " ")
        shapes = re.sub(r"\s+", " ", shapes)
        lines.append(row(fm, shapes))

    lines += routes_section()
    return "\n".join(lines) + "\n"


def main():
    content = build()
    if "--check" in sys.argv:
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as fh:
                on_disk = fh.read()
        else:
            on_disk = ""
        if on_disk != content:
            print("agent-routing-table.md is stale — run scripts/generate-routing-table.py", file=sys.stderr)
            sys.exit(1)
        print("agent-routing-table.md up to date")
        return
    with open(OUT, "w") as fh:
        fh.write(content)
    n = len(glob.glob(os.path.join(REPO, "agents", "genius", "*.md"))) - 1  # minus INDEX.md
    print(f"wrote {OUT}: {n} agents, {len(content)} bytes")


if __name__ == "__main__":
    main()
