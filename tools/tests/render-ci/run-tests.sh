#!/usr/bin/env bash
# Regression suite for `scripts/setup.sh render-ci <target>` (scripts/lib/
# render-ci.sh), plan docs/superpowers/plans/2026-10-22-single-ci-plan.md
# task 1.4.

#   T1  no target: usage on stderr, exit 2
#   T2  renders .github/workflows/pipeline.yml and exits 0
#   T3  all three files match the checked-in canonical-derived workflow set
#   T4  the header names the template's blob id (git hash-object)
#   T5  ci.json is written from templates/ci/ci.example.json when absent
#   T6  a second run changes no byte
#   T7  an existing ci.json is kept untouched

set -uo pipefail

cd "$(dirname "$0")" || { echo "FATAL: cannot cd to suite directory $(dirname "$0")" >&2; exit 1; }
REPO="$(git rev-parse --show-toplevel 2>/dev/null || (cd ../../.. && pwd))"
SETUP="$REPO/scripts/setup.sh"
TEMPLATE="$REPO/templates/ci/pipeline.yml"
EXAMPLE="$REPO/templates/ci/ci.example.json"

pass=0
fail=0
ok()  { pass=$(( pass + 1 )); printf '  ok   %s\n' "$1"; }
bad() { fail=$(( fail + 1 )); printf '  FAIL %s\n' "$1"; }

WORK="$(mktemp -d "${TMPDIR:-/tmp}/render-ci.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
TARGET="$WORK/target"
mkdir -p "$TARGET"
# A plugin-context variable would redirect PLUGIN_ROOT away from this checkout.
render() { env -u CLAUDE_PLUGIN_ROOT bash "$SETUP" render-ci "$@"; }

# T1
err="$(render 2>&1 >/dev/null)"; rc=$?
if [[ $rc -eq 2 && "$err" == *usage* ]]; then ok "no target: usage, exit 2"
else bad "no target: expected usage + exit 2, got rc=$rc: $err"; fi

# T2
out="$(render "$TARGET" 2>&1)"; rc=$?
RENDERED="$TARGET/.github/workflows/pipeline.yml"
if [[ $rc -eq 0 && -f "$RENDERED" ]]; then ok "renders pipeline.yml (exit 0)"
else bad "render rc=$rc, file present: $([[ -f "$RENDERED" ]] && echo yes || echo no)"; printf '%s\n' "$out" | sed 's/^/       | /'; fi

# T3: Python profile tests separately compare every common job to the canon.
same=true
for name in pipeline.yml pipeline-post-merge.yml pipeline-after-merge.yml; do
  cmp -s "$TARGET/.github/workflows/$name" "$REPO/.github/workflows/$name" || same=false
done
if [[ "$same" == true ]]; then ok "all three workflows match the checked-in render"
else bad "workflow set differs from the checked-in render"; fi

# T4
sha="$(git hash-object "$TEMPLATE")"
if [[ "$(head -n 1 "$RENDERED" 2>/dev/null)" == "# generated by zetetic-team-subagents render-ci $sha" ]]; then
  ok "header names the template blob id $sha"
else bad "header is: $(head -n 1 "$RENDERED" 2>/dev/null)"; fi

# T5
if cmp -s "$TARGET/ci.json" "$EXAMPLE"; then ok "ci.json written from the example"
else bad "ci.json missing or differs from the example"; fi

# T6
before="$(cd "$TARGET" && find . -type f -exec shasum -a 256 {} + | sort)"
out="$(render "$TARGET" 2>&1)"; rc=$?
after="$(cd "$TARGET" && find . -type f -exec shasum -a 256 {} + | sort)"
if [[ $rc -eq 0 && "$before" == "$after" && "$out" == *Unchanged* ]]; then ok "second run changes no byte"
else bad "second run rc=$rc, changed: $(diff <(echo "$before") <(echo "$after") | head -3)"; fi

# T7
printf '{"unit": "mine"}\n' > "$TARGET/ci.json"
render "$TARGET" >/dev/null 2>&1
if [[ "$(cat "$TARGET/ci.json")" == '{"unit": "mine"}' ]]; then ok "an existing ci.json is kept"
else bad "an existing ci.json was overwritten"; fi

printf '\nrender-ci: %d passed, %d failed\n' "$pass" "$fail"
[[ $fail -eq 0 ]]
